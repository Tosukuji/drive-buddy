import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 400, height: 860 }, locale: 'ja-JP', permissions: ['geolocation'], geolocation: { latitude: 35.6580, longitude: 139.7016, accuracy: 15 } });
const page = await ctx.newPage();
const logs = [];
page.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
await page.route('https://fonts.**', (r) => r.abort());
await page.route('https://nominatim.openstreetmap.org/**', (r) => {
  const u = new URL(r.request().url()); const lat = Number(u.searchParams.get('lat'));
  const address = lat > 35.6 ? { state: '東京都', city: '渋谷区', suburb: '道玄坂' } : { state: '神奈川県', city: '横浜市', city_district: '西区' };
  r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ address }) });
});
await page.goto('http://127.0.0.1:8766/');
await page.waitForFunction(() => document.querySelector('#loading').hidden, null, { timeout: 60000 });
await page.click('#go-check');
await page.click('#depart-skip');
await page.waitForTimeout(2500);
await ctx.setGeolocation({ latitude: 35.4437, longitude: 139.6380, accuracy: 15 });
await page.waitForTimeout(2500);
await page.focus('#arrive-btn'); await page.keyboard.press('Enter');
await page.waitForTimeout(2500);
await page.screenshot({ path: 'shots/place-arrive.png', clip: { x: 0, y: 380, width: 400, height: 480 } });
await page.click('#save-drive');
await page.waitForTimeout(500);
await page.click('#open-history');
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/place-history.png', clip: { x: 0, y: 0, width: 400, height: 330 } });
console.log(await page.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem('drive-buddy-state-v1')).drives[0])));
console.log(logs.join('\n') || 'no page errors');
await browser.close();
