import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 400, height: 860 }, locale: 'ja-JP' });
const page = await ctx.newPage();
const logs = [], outside = new Set();
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(m.type() + ': ' + m.text()); });
page.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
page.on('request', (r) => { const u = new URL(r.url()); if (u.hostname !== '127.0.0.1') outside.add(u.hostname); });
await page.route('https://fonts.**', (r) => r.abort());
const t0 = Date.now();
await page.goto('http://127.0.0.1:8766/');
await page.waitForFunction(() => document.querySelector('#loading').hidden && !document.querySelector('#fallback').hidden === false, null, { timeout: 60000 });
console.log('model ready in', Date.now() - t0, 'ms');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/site-home.png' });
const sw = await page.evaluate(async () => { const r = await navigator.serviceWorker.getRegistration(); return !!r; });
const manifest = await page.evaluate(() => fetch('manifest.webmanifest').then((r) => r.json()).then((j) => j.name));
const storage = await page.evaluate(() => document.querySelector('#store-note') && window.localStorage.getItem('drive-buddy-state-v1-probe'));
console.log('service worker:', sw, '| manifest:', manifest, '| local storage probe:', storage);
console.log('outside hosts requested:', [...outside].join(', ') || 'none');
console.log(logs.filter((l) => !l.includes('ERR_FAILED') && !l.includes('Failed to load resource')).join('\n') || 'no errors');
await browser.close();
